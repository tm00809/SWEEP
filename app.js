// ===== Trait Tiers =====
// 羁绊多级阈值：levels 数组（如 [3,5]），兼容旧的单一 required 字段
function traitLevels(syn) {
  if (!syn) return [];
  if (Array.isArray(syn.levels) && syn.levels.length) return [...syn.levels].sort((a, b) => a - b);
  return [syn.required || 1];
}
// 下一个待达成的阈值；全部达成时返回最大档
function traitNextLevel(syn, count) {
  const lv = traitLevels(syn);
  return lv.find(l => count < l) ?? lv[lv.length - 1];
}
// 阈值展示串，如 "3/5"，已达成的档位加 on 类
function traitTierMarks(syn, count) {
  return traitLevels(syn)
    .map(l => `<span class="tier${count >= l ? ' on' : ''}">${l}</span>`)
    .join('<i>/</i>');
}

