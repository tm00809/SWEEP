// 当前队伍自动保存到 localStorage（按赛季隔离）；另支持命名方案存/取/删
function teamStorageKey(num) { return `sle_team_s${num}`; }
function plansStorageKey(num) { return `sle_plans_s${num}`; }

function serializeTeam() {
  return {
    size: state.teamSize,
    team: state.team.map(m => m ? {
      id: m.operator.id,
      stars: m.stars || 1,
      eq: (m.equipment || [null, null]).map(e => e || null),
      syn: m.operator.synSelectable ? m.operator.synergies : undefined, // V22 假人自选羁绊
    } : null),
    bench: state.bench.map(b => b ? {
      id: b.operator.id,
      stars: b.stars || 1,
      syn: b.operator.synSelectable ? b.operator.synergies : undefined, // V22
    } : null), // V21
  };
}

function restoreTeam(data) {
  if (!data || !Array.isArray(data.team)) return;
  const opData = getSeasonData().operatorData;
  const team = data.team.map(entry => {
    if (!entry) return null;
    const op = opData.find(o => o.id === entry.id);
    if (!op) return null; // 干员数据更新后可能失效，跳过
    // V22：假人恢复自选羁绊（克隆）
    if (entry.syn && op.synSelectable) {
      return { operator: { ...op, synergies: entry.syn }, equipment: entry.eq || [null, null], stars: entry.stars || 1 };
    }
    return { operator: op, equipment: entry.eq || [null, null], stars: entry.stars || 1 };
  });
  while (team.length && !team[team.length - 1]) team.pop();
  if (data.size === 9) state.teamSize = 9;
  state.team = team.filter(Boolean);
  // V21：恢复备战席
  if (Array.isArray(data.bench)) {
    state.bench = Array(10).fill(null).map((_, i) => {
      const e = data.bench[i];
      if (!e) return null;
      const op = opData.find(o => o.id === e.id);
      if (!op) return null;
      if (e.syn && op.synSelectable) return { operator: { ...op, synergies: e.syn }, stars: e.stars || 1 };
      return { operator: op, stars: e.stars || 1 };
    });
  }
}

