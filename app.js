// ===== Event Listeners =====
function setupEventListeners() {
  // --- Click delegation ---
  document.addEventListener('click', (e) => {
    // Season switcher chip（横向滚动切换条）
    const seasonChip = e.target.closest('.season-chip');
    if (seasonChip) {
      showSeason(parseInt(seasonChip.dataset.season));
      return;
    }

    // Season switcher arrows
    if (e.target.closest('#season-prev')) {
      switchSeason(-1);
      return;
    }
    if (e.target.closest('#season-next')) {
      switchSeason(1);
      return;
    }

    // Tab
    const tab = e.target.closest('.tab');
    if (tab) {
      switchTab(tab.dataset.tab);
      return;
    }

    // Operator sort mode toggle
    const sortBtn = e.target.closest('.sort-btn');
    if (sortBtn) {
      const mode = sortBtn.dataset.sort;
      if (mode !== state.operatorSortMode) {
        state.operatorSortMode = mode;
        renderOperators();
      }
      return;
    }

    // 羁绊多选筛选 chip（AND 检索）
    const synChip = e.target.closest('.syn-filter-chip');
    if (synChip) {
      const key = synChip.dataset.syn;
      const idx = state.selectedSynergies.indexOf(key);
      if (idx >= 0) state.selectedSynergies.splice(idx, 1);
      else state.selectedSynergies.push(key);
      renderOperators();
      return;
    }

    // 清空羁绊筛选
    if (e.target.closest('.syn-filter-clear')) {
      state.selectedSynergies = [];
      renderOperators();
      return;
    }

    // 队伍槽位星级切换（一星/二星）
    const starBtn = e.target.closest('.star-btn');
    if (starBtn) {
      const idx = parseInt(starBtn.dataset.slotIndex);
      const member = state.team[idx];
      if (member) {
        member.stars = parseInt(starBtn.dataset.stars);
        renderTeam();
        renderSynergies(); // 同步总费用
      }
      return;
    }

    // 队伍模式切换（标准8人 / 九人队伍）
    const modeBtn = e.target.closest('.team-mode-btn');
    if (modeBtn) {
      requestTeamSize(parseInt(modeBtn.dataset.mode));
      return;
    }

    // Strategy apply button
    const applyBtn = e.target.closest('.strategy-apply-btn');
    if (applyBtn && !applyBtn.disabled) {
      applyStrategy(parseInt(applyBtn.dataset.strategyId));
      return;
    }

    // Operator card → add to team
    const opCard = e.target.closest('.operator-card');
    if (opCard) {
      addOperator(parseInt(opCard.dataset.opId));
      return;
    }

    // Remove operator button
    const removeBtn = e.target.closest('.slot-remove');
    if (removeBtn) {
      e.stopPropagation();
      removeOperator(parseInt(removeBtn.dataset.slotIndex));
      return;
    }

    // Remove equipment button
    const equipRemove = e.target.closest('.equip-remove');
    if (equipRemove) {
      e.stopPropagation();
      removeEquipment(
        parseInt(equipRemove.dataset.parentSlot),
        parseInt(equipRemove.dataset.equipIndex)
      );
      return;
    }

    // V17 档案柜：打开 / 保存 / 载入 / 销毁
    if (e.target.closest('#plans-btn')) {
      openPlansModal();
      return;
    }
    // V18 云端登录
    if (e.target.closest('#auth-btn')) {
      if (!cloud) {
        showConfirmModal('云端档案尚未配置。需要在 app.js 顶部填入 Supabase 项目地址和密钥。', null, '云端未配置');
        return;
      }
      openAuthModal();
      return;
    }
    if (e.target.id === 'auth-login-btn') {
      doCloudLogin();
      return;
    }
    if (e.target.id === 'auth-logout-btn') {
      cloudLogout();
      hideModal('auth-modal');
      return;
    }
    if (e.target.id === 'auth-cancel-btn') {
      hideModal('auth-modal');
      return;
    }
    if (e.target.id === 'plan-save-btn') {
      saveCurrentPlan();
      return;
    }
    if (e.target.id === 'plan-close') {
      hideModal('plan-modal');
      return;
    }
    const loadBtn = e.target.closest('.plan-load-btn');
    if (loadBtn) {
      loadPlanByRef(loadBtn.dataset.planType || 'l', parseInt(loadBtn.dataset.planIndex));
      return;
    }
    const deleteBtn = e.target.closest('.plan-delete-btn');
    if (deleteBtn) {
      deletePlanByRef(deleteBtn.dataset.planType || 'l', parseInt(deleteBtn.dataset.planIndex));
      return;
    }

    // V22 假人羁绊伪造弹窗
    if (e.target.id === 'dummy-confirm-btn') {
      confirmDummyAdd();
      return;
    }
    if (e.target.id === 'dummy-cancel-btn') {
      dummyPending = null;
      hideModal('dummy-modal');
      return;
    }
    const dummyChip = e.target.closest('.dummy-syn-chip');
    if (dummyChip) {
      dummyChip.classList.toggle('selected');
      return;
    }

    // V21 备战席：调入队伍 / 移出
    const benchRemove = e.target.closest('.bench-remove');
    if (benchRemove) {
      e.stopPropagation();
      removeBench(parseInt(benchRemove.dataset.benchIndex));
      saveTeamAuto();
      return;
    }
    const benchSlot = e.target.closest('.bench-slot.filled');
    if (benchSlot) {
      moveBenchToTeam(parseInt(benchSlot.dataset.benchIndex));
      saveTeamAuto();
      return;
    }

    // V23 队伍面板显隐
    if (e.target.id === 'panel-toggle-btn') {
      const hidden = document.body.classList.toggle('editor-hidden');
      e.target.textContent = hidden ? '▼ 展开队伍' : '▲ 收起队伍';
      return;
    }

    if (e.target.closest('.generate-btn')) {
      generateTeam();
      return;
    }

    // Confirm modal — yes
    if (e.target.id === 'confirm-yes') {
      hideModal('confirm-modal');
      if (state.confirmCallback) {
        const cb = state.confirmCallback;
        state.confirmCallback = null;
        cb();
      }
      return;
    }

    // Confirm modal — no
    if (e.target.id === 'confirm-no') {
      hideModal('confirm-modal');
      state.confirmCallback = null;
      return;
    }

    // Equipment replace modal — cancel
    if (e.target.id === 'equip-cancel') {
      hideModal('equip-modal');
      return;
    }

    // Operator detail modal — close
    if (e.target.id === 'op-detail-close') {
      hideModal('op-detail-modal');
      return;
    }

    // Result modal — close
    if (e.target.id === 'result-close') {
      hideModal('result-modal');
      return;
    }

    // Click overlay to close (only for result & equip modals, not confirm)
    if (e.target.id === 'modal-overlay') {
      const confirmVisible = !document.getElementById('confirm-modal').classList.contains('hidden');
      if (confirmVisible) return; // Don't close confirm by clicking overlay
      hideAllModals();
      return;
    }
  });

  // --- 右键干员卡查看简介 ---
  document.addEventListener('contextmenu', (e) => {
    const opCard = e.target.closest('.operator-card');
    if (opCard) {
      e.preventDefault();
      showOperatorDetail(parseInt(opCard.dataset.opId));
      return;
    }
    // V19：右键装备卡看详情
    const eqCard = e.target.closest('.equipment-card');
    if (eqCard) {
      e.preventDefault();
      showEquipmentDetail(parseInt(eqCard.dataset.equipId));
    }
  });

  // --- Drag and drop for equipment ---
  document.addEventListener('dragstart', (e) => {
    const card = e.target.closest('.equipment-card');
    if (card) {
      e.dataTransfer.setData('text/plain', card.dataset.equipId);
      e.dataTransfer.effectAllowed = 'copy';
      card.classList.add('dragging');
    }
  });

  document.addEventListener('dragend', (e) => {
    const card = e.target.closest('.equipment-card');
    if (card) {
      card.classList.remove('dragging');
    }
    document.querySelectorAll('.team-slot.drag-over').forEach(el => {
      el.classList.remove('drag-over');
    });
  });

  document.addEventListener('dragover', (e) => {
    const slot = e.target.closest('.team-slot');
    if (slot && slot.classList.contains('filled')) {
      e.preventDefault();
      e.dataTransfer.dropEffect = 'copy';
      slot.classList.add('drag-over');
    }
  });

  document.addEventListener('dragleave', (e) => {
    const slot = e.target.closest('.team-slot');
    if (slot && !slot.contains(e.relatedTarget)) {
      slot.classList.remove('drag-over');
    }
  });

  document.addEventListener('drop', (e) => {
    const slot = e.target.closest('.team-slot');
    if (slot && slot.classList.contains('filled')) {
      e.preventDefault();
      slot.classList.remove('drag-over');
      const equipId = parseInt(e.dataTransfer.getData('text/plain'));
      const slotIndex = parseInt(slot.dataset.slotIndex);
      equipToSlot(slotIndex, equipId);
    }
  });

  // V17 档案柜：输入框回车直接存档
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' && e.target.id === 'plan-name-input') {
      e.preventDefault();
      saveCurrentPlan();
    }
    // V18：登录框回车直接登录
    if (e.key === 'Enter' && (e.target.id === 'auth-code-input' || e.target.id === 'auth-pin-input')) {
      e.preventDefault();
      doCloudLogin();
    }
  });
}

