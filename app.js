// 星级费用规则：一星 = 基础费用；二星 = 3 张一星合成，费用×3
function memberCost(member) {
  if (!member) return 0;
  return member.operator.cost * (member.stars === 2 ? 3 : 1);
}

// 队伍总费用（按星级折算）
function teamTotalCost() {
  return state.team.reduce((sum, m) => sum + memberCost(m), 0);
}

