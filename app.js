function renderSynergies() {
  const container = document.getElementById('synergy-list');
  const { synergyData } = getSeasonData();
  const counts = {};
  const seenNames = new Set();

  state.team.forEach(member => {
    if (member) {
      const opName = member.operator.name;
      if (opName && seenNames.has(opName)) return; // 同名干员不累加羁绊
      if (opName) seenNames.add(opName);
      member.operator.synergies.forEach(syn => {
        counts[syn] = (counts[syn] || 0) + 1;
      });
      // V24：转职装备附加盟约（与干员自身盟约重复时不重复计数）
      (member.equipment || []).forEach(eqId => {
        if (!eqId) return;
        const eq = getEquipment(eqId);
        if (eq && eq.syn && !member.operator.synergies.includes(eq.syn)) {
          counts[eq.syn] = (counts[eq.syn] || 0) + 1;
        }
      });
    }
  });

  const keys = Object.keys(counts);
  // 总费用显示（羁绊条上方，随星级折算）
  document.getElementById('team-total-cost').textContent = teamTotalCost();
  if (keys.length === 0) {
    container.innerHTML = '<span class="synergy-empty">添加干员后显示羁绊</span>';
    return;
  }

  container.innerHTML = '';
  keys.forEach(key => {
    const syn = synergyData[key];
    const count = counts[key];
    const lv = traitLevels(syn);
    const active = count >= lv[0];
    const maxed = count >= lv[lv.length - 1];
    const pill = document.createElement('div');
    pill.className = `synergy-pill${active ? ' active' : ''}${maxed ? ' maxed' : ''}`;
    pill.innerHTML = `
      <span>${syn.name}</span>
      <span class="tiers">${traitTierMarks(syn, count)}</span>
      <span class="count">${count}</span>
    `;
    container.appendChild(pill);
  });
}

