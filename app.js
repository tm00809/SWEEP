// 相邻赛季切换（delta: -1 / +1）
function switchSeason(delta) {
  const nums = Object.keys(seasonsConfig).map(Number).sort((a, b) => a - b);
  const idx = nums.indexOf(state.currentSeason);
  const next = nums[idx + delta];
  if (next !== undefined) showSeason(next);
}

// 更新切换条状态：高亮当前赛季、滚动到可视区、箭头边界禁用
function updateSeasonSwitcher() {
  const bar = document.getElementById('season-switcher');
  const nums = Object.keys(seasonsConfig).map(Number).sort((a, b) => a - b);
  const idx = nums.indexOf(state.currentSeason);
  bar.querySelectorAll('.season-chip').forEach(chip => {
    chip.classList.toggle('active', Number(chip.dataset.season) === state.currentSeason);
  });
  const activeChip = bar.querySelector('.season-chip.active');
  if (activeChip) {
    activeChip.scrollIntoView({ behavior: 'smooth', inline: 'center', block: 'nearest' });
  }
  document.getElementById('season-prev').disabled = idx <= 0;
  document.getElementById('season-next').disabled = idx >= nums.length - 1;
}

